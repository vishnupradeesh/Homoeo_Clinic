import json
import os
import urllib.error
import urllib.request


SYSTEM_PROMPT = (
    "You are Arokya Assistant, a friendly guide for the Arokya Homoeo Clinic "
    "web application. The clinic offers holistic homoeopathic care and "
    "cosmetology consultations led by Dr. Vilasini Veeraraghavan "
    "(B.H.M.S., Cosmetologist). "
    "Help all users understand how to use the app: patients can register a "
    "membership, book appointments, and view their profile; doctors can "
    "manage patients, tasks, and appointments after admin approval. "
    "Give clear, concise, encouraging answers. "
    "You do not provide medical diagnoses; for clinical concerns, advise the "
    "user to book an appointment with the doctor."
)


class ChatService:
    """Conversational assistant backed by an open-source LLM.

    Uses a locally hosted open-source model served by Ollama
    (https://ollama.com) via its HTTP API. Configure with environment
    variables (e.g. in backend/.env):

      OLLAMA_HOST     default http://localhost:11434
      OLLAMA_MODEL    default llama3.2  (any pulled open-source model)
      CHAT_TIMEOUT    request timeout in seconds, default 60

    When no model server is reachable, replies are generated by a built-in
    rule-based guide so the assistant keeps working in development.
    """

    def __init__(self) -> None:
        self.host = os.environ.get(
            "OLLAMA_HOST", "http://localhost:11434"
        ).rstrip("/")
        self.model = os.environ.get("OLLAMA_MODEL", "llama3.2:1b")
        self.timeout = int(os.environ.get("CHAT_TIMEOUT", "60"))

    def reply(
        self, message: str, history: list
    ) -> tuple[str, str, bool]:
        """Return (reply_text, model_name, simulated)."""

        messages = [{"role": "system", "content": SYSTEM_PROMPT}]

        # Keep the last few turns for context.
        for item in history[-10:]:
            role = getattr(item, "role", None)
            content = getattr(item, "content", None)
            if role in ("user", "assistant") and content:
                messages.append({"role": role, "content": content})

        messages.append({"role": "user", "content": message})

        text = self._call_ollama(messages)

        if text:
            return text, self.model, False

        return self._fallback(message), "rule-based", True

    # ----- Open-source model (Ollama) -----

    def _call_ollama(self, messages: list[dict]) -> str | None:
        payload = json.dumps(
            {
                "model": self.model,
                "messages": messages,
                "stream": False,
            }
        ).encode("utf-8")

        request = urllib.request.Request(
            f"{self.host}/api/chat",
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(
                request, timeout=self.timeout
            ) as response:
                data = json.loads(response.read().decode("utf-8"))

            content = (data.get("message") or {}).get("content", "")
            return content.strip() or None
        except (urllib.error.URLError, TimeoutError, ValueError, OSError):
            # Server unreachable or unexpected response - use fallback.
            return None

    # ----- Rule-based fallback -----

    def _fallback(self, message: str) -> str:
        text = message.lower()

        if any(word in text for word in ("appointment", "book", "booking")):
            return (
                "To book an appointment, sign in as a patient and open the "
                "Appointments page, then choose a preferred date and add a "
                "short note about your concern."
            )

        if any(word in text for word in ("register", "sign up", "membership")):
            return (
                "You can join from the login screen. Choose 'Patient' to "
                "create a membership instantly, or 'Doctor' to request an "
                "account that an administrator will approve."
            )

        if any(word in text for word in ("doctor", "vilasini", "who")):
            return (
                "Dr. Vilasini Veeraraghavan (B.H.M.S., Cosmetologist) leads "
                "the clinic, offering holistic homoeopathic care and "
                "cosmetology consultations."
            )

        if any(word in text for word in ("login", "sign in", "password")):
            return (
                "Sign in with your username or mobile number and password. "
                "Doctor accounts must be approved by an admin before first "
                "sign-in."
            )

        if any(word in text for word in ("hi", "hello", "hey", "help")):
            return (
                "Hello! I'm the Arokya Assistant. I can help you register, "
                "book appointments, or find your way around the app. What "
                "would you like to do?"
            )

        return (
            "I'm here to help you use the Arokya Homoeo Clinic app - "
            "registering, booking appointments, or navigating your account. "
            "For medical concerns, please book an appointment with the doctor."
        )
